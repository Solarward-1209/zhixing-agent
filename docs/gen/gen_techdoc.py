def pick_font(paths):
    for p in paths:
        if os.path.exists(p):
            return p
    return None


def register(name, paths, **kwargs):
    p = pick_font(paths)
    if p is None:
        return False
    try:
        pdfmetrics.registerFont(TTFont(name, p, **kwargs))
        return True
    except Exception:
        return False


