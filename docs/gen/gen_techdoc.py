class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


def add_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1(story, text):
    story.append(CondPageBreak(H1_ORPHAN))
    story.extend([
        KeepTogether([
            add_heading(text, S['h1'], level=0),
            HRFlowable(width='100%', thickness=1.2, color=ACCENT, spaceBefore=2, spaceAfter=10),
        ]),
    ])


def h2(story, text):
    story.append(CondPageBreak(H1_ORPHAN * 0.6))
    story.append(add_heading(text, S['h2'], level=1))


def h3(story, text):
    story.append(Paragraph('<b>%s</b>' % text, S['h3']))


def body(story, text, indent=True):
    story.append(Paragraph(text, S['body'] if indent else S['body_ni']))


def bullets(story, items):
    for it in items:
        story.append(Paragraph('· %s' % it, S['bullet']))
    story.append(Spacer(1, 5))


def make_table(story, headers, rows, ratios, caption=None, center_cols=()):
    data = [[Paragraph('<b>%s</b>' % h, S['th']) for h in headers]]
    for r in rows:
        cells = []
        for ci, c in enumerate(r):
            st = S['td_c'] if ci in center_cols else S['td']
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    widths = [x * AVAIL_W for x in ratios]
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(('BACKGROUND', (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 8))
    if caption:
        block = [t, Paragraph(caption, S['caption'])]
        if len(rows) <= 12:
            story.append(KeepTogether(block))
        else:
            story.append(t)
            story.append(Paragraph(caption, S['caption']))
    else:
        story.append(t)
    story.append(Spacer(1, 8))


def callouts(story, items):
    """并排数据卡片：items = [(big, label), ...]"""
    n = len(items)
    box_w = (AVAIL_W - (n - 1) * 12) / n
    cells = []
    for big, label in items:
        inner = Table(
            [[Paragraph('<b>%s</b>' % big, S['stat'])], [Paragraph(label, S['stat_label'])]],
            colWidths=[box_w - 2],
        )
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 0.8, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ]))
        cells.append(inner)
    wrap = Table([cells], colWidths=[box_w + (12 if i < n - 1 else 0) for i in range(n)], hAlign='CENTER')
    wrap.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    story.append(Spacer(1, 6))
    story.append(KeepTogether(wrap))
    story.append(Spacer(1, 10))


